#!/usr/bin/env python3
"""Generate llms.txt from docs.json navigation and each page's frontmatter.

Usage:
    python3 scripts/gen_llms_txt.py           # write llms.txt
    python3 scripts/gen_llms_txt.py --check   # exit 1 if llms.txt is out of date

Sections follow the navigation groups, in navigation order. Only pages that
are listed in docs.json and exist on disk are published. The API reference
endpoint list is the one hand-kept part (OpenAPI pages are generated by
Mintlify and have no local files), see REFERENCE below.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://www.vaquill.ai/docs"

PREAMBLE = """# Vaquill

> Vaquill is US primary law data infrastructure, delivered through a REST API, an MCP server and SQL over an object store. Every result carries a citation, full text and a link to the official government source.

Base URL: https://api.vaquill.ai. Authenticate every request with `Authorization: Bearer vq_key_...`. Coverage and counts live on the [Coverage](https://www.vaquill.ai/docs/api-guide/coverage) page.
"""

# Hand-kept: the OpenAPI endpoint pages are generated by Mintlify.
REFERENCE = [
    ("Search US statutes", "us-statutes/search-us-statutes-constitutions-court-rules-and-executive-actions", "POST /api/v1/us/statutes/search."),
    ("Get statute section metadata", "us-statutes/get-statute-section-metadata", "GET /api/v1/us/statutes/section/{act_id}."),
    ("Get statute full text", "us-statutes/get-statute-full-text", "GET /api/v1/us/statutes/section/{act_id}/body."),
    ("Get metadata for many statute sections", "us-statutes/get-metadata-for-many-statute-sections", "POST /api/v1/us/statutes/sections."),
    ("Resolve a citation to its section", "us-statutes/resolve-a-citation-to-its-section", "GET /api/v1/us/statutes/resolve."),
    ("Get the sections around this one", "us-statutes/get-the-sections-around-this-one", "GET /api/v1/us/statutes/section/{act_id}/related."),
    ("Coverage matrix by jurisdiction and corpusType", "us-statutes/coverage-matrix-by-jurisdiction-and-corpustype", "GET /api/v1/us/statutes/coverage."),
    ("Browse the statutory hierarchy", "us-statutes/browse-the-statutory-hierarchy", "GET /api/v1/us/statutes/divisions."),
    ("List watchable boards", "board-watches/list-watchable-boards", "GET /api/v1/boards, the entry point for the free law-change alert endpoints."),
    ("Get API credit pricing", "pricing/get-api-credit-pricing", "GET /api/v1/api-credits/pricing, public and unauthenticated."),
]
OPENAPI_LINKS = [
    ("OpenAPI schema (US)", "https://api.vaquill.ai/external/openapi.json", "Machine-readable spec for all public US endpoints."),
]

# Navigation groups that go under the llms.txt "Optional" heading.
OPTIONAL_GROUPS = {"Releases"}


def read_frontmatter(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    out: dict[str, str] = {}
    if not m:
        return out
    for line in m.group(1).splitlines():
        km = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if not km:
            continue
        value = km.group(2).strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        out[km.group(1)] = value
    return out


class Section:
    def __init__(self, name: str) -> None:
        self.name = name
        self.pages: list[str] = []


def collect(group: dict, sections: list[Section], name_override: str | None = None) -> None:
    section = Section(name_override or group.get("group", ""))
    sections.append(section)
    if group.get("root"):
        section.pages.append(group["root"])
    nested: list[dict] = []
    for item in group.get("pages", []):
        if isinstance(item, str):
            section.pages.append(item)
        elif isinstance(item, dict):
            nested.append(item)
    for item in nested:
        collect(item, sections)


def build_sections(docs: dict) -> list[Section]:
    sections: list[Section] = []
    for tab in docs["navigation"]["tabs"]:
        for group in tab.get("groups", []):
            if group.get("pages") or group.get("root"):
                collect(group, sections)
    return [s for s in sections if s.pages]


def render() -> str:
    docs = json.loads((ROOT / "docs.json").read_text(encoding="utf-8"))
    sections = build_sections(docs)
    lines: list[str] = [PREAMBLE.rstrip("\n"), ""]
    seen: set[str] = set()

    def entries(section: Section) -> list[str]:
        out = []
        for page in section.pages:
            if page in seen:
                continue
            f = ROOT / f"{page}.mdx"
            if not f.exists():
                print(f"warning: {page} is in docs.json but {f.name} is missing", file=sys.stderr)
                continue
            seen.add(page)
            fm = read_frontmatter(f)
            title = fm.get("title", page.rsplit("/", 1)[-1])
            desc = fm.get("description", "")
            line = f"- [{title}]({BASE}/{page})"
            if desc:
                line += f": {desc}"
            out.append(line)
        return out

    optional: list[str] = []
    for section in sections:
        body = entries(section)
        if not body:
            continue
        if section.name in OPTIONAL_GROUPS:
            optional.extend(body)
            continue
        lines += [f"## {section.name}", ""] + body + [""]

    lines += ["## API reference", ""]
    for title, slug, desc in REFERENCE:
        lines.append(f"- [{title}]({BASE}/api-reference/{slug}): {desc}")
    for title, url, desc in OPENAPI_LINKS:
        lines.append(f"- [{title}]({url}): {desc}")
    lines.append("")
    if optional:
        lines += ["## Optional", ""] + optional + [""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    target = ROOT / "llms.txt"
    new = render()
    if "--check" in sys.argv:
        old = target.read_text(encoding="utf-8") if target.exists() else ""
        if old != new:
            print("llms.txt is out of date. Run: python3 scripts/gen_llms_txt.py", file=sys.stderr)
            return 1
        print("llms.txt is up to date.")
        return 0
    target.write_text(new, encoding="utf-8")
    print(f"wrote {target} ({new.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
